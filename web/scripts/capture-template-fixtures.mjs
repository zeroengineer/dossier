// Capture `GET /api/templates` and `GET /api/templates/:id` for every built-in template from a throwaway copy of the
// example workspace and write them to web/src/test/fixtures-generate.ts (used by the Generate tests). `meta.params`
// (layout parameters, large and unused by the form) is left out to keep the fixture small.
// Run from the repo root after changing a built-in template's fields: node web/scripts/capture-template-fixtures.mjs
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { initWorkspace } from '../../src/workspace/index.js';
import { openContext } from '../../src/context.js';
import { buildServer } from '../../src/server.js';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'test', 'fixtures-generate.ts');
const tmp = mkdtempSync(join(tmpdir(), 'dossier-fixtures-'));
let ctx;
let app;
try {
  const home = initWorkspace(join(tmp, 'ws'));
  ctx = openContext({ home, user: 'demo', env: {} });
  app = buildServer(ctx, { spaDir: join(tmp, 'no-dist') });
  const list = (await app.inject({ method: 'GET', url: '/api/templates' })).json();
  const details = {};
  for (const t of list.templates.filter((x) => x.source === 'builtin')) {
    const res = await app.inject({ method: 'GET', url: `/api/templates/${encodeURIComponent(t.id)}` });
    if (res.statusCode !== 200) throw new Error(`${t.id}: HTTP ${res.statusCode} ${res.body}`);
    const detail = res.json();
    details[t.id] = { ...detail, meta: { ...detail.meta, params: {} } };
  }
  const json = (v) => JSON.stringify(v, null, 2);
  writeFileSync(out, [
    '// Generated by web/scripts/capture-template-fixtures.mjs from the example workspace (Acme Events). Do not edit by hand.',
    'import type { TemplateDetail, TemplateList } from "@/api/types"',
    '',
    '/** `GET /api/templates` of the example workspace (built-in templates only). */',
    `export const builtinTemplateList: TemplateList = ${json({ templates: list.templates.filter((x) => x.source === 'builtin'), errors: [] })}`,
    '',
    '/** `GET /api/templates/:id` for every built-in template, by id (`meta.params` emptied). */',
    `export const builtinTemplateDetails: Record<string, TemplateDetail> = ${json(details)}`,
    '',
  ].join('\n'));
  console.log(`wrote ${Object.keys(details).length} templates to ${out}`);
} finally {
  await app?.close();
  ctx?.close();
  rmSync(tmp, { recursive: true, force: true });
}
